/**
 * En ny idempotensnyckel (uuid v4) för ett inskick av en runda. `crypto.randomUUID` finns bara i säkra sammanhang
 * (https/localhost); utanför dem byggs en v4 ur `crypto.getRandomValues`, så att loggningen inte går sönder i en dev-server över http.
 */
export function newIdempotencyKey(): string {
  if (typeof crypto.randomUUID === 'function') return crypto.randomUUID();
  const bytes = crypto.getRandomValues(new Uint8Array(16));
  bytes[6] = (bytes[6] & 0x0f) | 0x40; // version 4
  bytes[8] = (bytes[8] & 0x3f) | 0x80; // variant 10xx
  const hex = Array.from(bytes, (b) => b.toString(16).padStart(2, '0')).join('');
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}
